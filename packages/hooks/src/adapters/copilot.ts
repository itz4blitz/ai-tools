import { existsSync } from "node:fs";
import { resolve } from "node:path";
import { registry, BaseAdapter } from "./index.js";
import type {
  AdapterCapabilities,
  GeneratedConfig,
  HookDefinition,
  HookEventType,
} from "../types/index.js";

/**
 * Event mapping: ai-hooks universal events -> GitHub Copilot native hooks.
 *
 * Copilot supports lifecycle hooks through `.github/hooks/*.json` with events:
 *   sessionStart, userPromptSubmit, preToolUse, postToolUse, stop, sessionEnd
 */
const EVENT_MAP: Record<string, string[]> = {
  "session:start": ["sessionStart"],
  "session:end": ["sessionEnd"],
  "prompt:submit": ["userPromptSubmit"],
  "prompt:response": ["stop"],
  "tool:before": ["preToolUse"],
  "tool:after": ["postToolUse"],
  "file:read": ["preToolUse"],
  "file:write": ["preToolUse"],
  "file:edit": ["preToolUse"],
  "file:delete": ["preToolUse"],
  "shell:before": ["preToolUse"],
  "shell:after": ["postToolUse"],
  "mcp:before": ["preToolUse"],
  "mcp:after": ["postToolUse"],
};

const REVERSE_MAP: Record<string, HookEventType[]> = {
  sessionStart: ["session:start"],
  userPromptSubmit: ["prompt:submit"],
  preToolUse: [
    "tool:before",
    "file:read",
    "file:write",
    "file:edit",
    "file:delete",
    "shell:before",
    "mcp:before",
  ],
  postToolUse: ["tool:after", "shell:after", "mcp:after"],
  stop: ["prompt:response", "session:end"],
  sessionEnd: ["session:end"],
};

const HOOKS_CONFIG_PATH = ".github/hooks/ai-tools-hooks.json";
const HOOKS_RUNNER_PATH = ".github/hooks/ai-tools-hooks-runner.js";

class CopilotAdapter extends BaseAdapter {
  readonly id = "copilot";
  readonly name = "Copilot";
  readonly version = "1.0";

  readonly capabilities: AdapterCapabilities = {
    beforeHooks: true,
    afterHooks: true,
    mcp: true,
    configFile: true,
    supportedEvents: [
      "session:start",
      "session:end",
      "prompt:submit",
      "prompt:response",
      "tool:before",
      "tool:after",
      "file:read",
      "file:write",
      "file:edit",
      "file:delete",
      "shell:before",
      "shell:after",
      "mcp:before",
      "mcp:after",
    ],
    blockableEvents: [
      "prompt:submit",
      "tool:before",
      "file:read",
      "file:write",
      "file:edit",
      "file:delete",
      "shell:before",
      "mcp:before",
    ],
  };

  async detect(): Promise<boolean> {
    const hasDir = existsSync(resolve(process.cwd(), ".github/hooks"));
    if (hasDir) return true;
    const hasCopilot = await this.commandExists("copilot");
    if (hasCopilot) return true;
    return this.commandExists("code");
  }

  async generate(hooks: HookDefinition[]): Promise<GeneratedConfig[]> {
    const configs: GeneratedConfig[] = [];

    const neededEvents = new Set<string>();
    for (const hook of hooks) {
      for (const event of hook.events) {
        for (const nativeEvent of this.mapEvent(event)) {
          neededEvents.add(nativeEvent);
        }
      }
    }

    configs.push({
      path: HOOKS_RUNNER_PATH,
      content: this.generateRunner(),
      format: "js",
    });

    const runnerFullPath = resolve(process.cwd(), HOOKS_RUNNER_PATH).replace(/\\/g, "/");
    const hooksConfig: Record<
      string,
      Array<{ type: "command"; command: string; timeout: number }>
    > = {};

    for (const event of neededEvents) {
      hooksConfig[event] = [
        {
          type: "command",
          command: `node "${runnerFullPath}" ${event}`,
          timeout: 30,
        },
      ];
    }

    configs.push({
      path: HOOKS_CONFIG_PATH,
      content: JSON.stringify({ version: 1, hooks: hooksConfig }, null, 2) + "\n",
      format: "json",
    });

    return configs;
  }

  mapEvent(event: HookEventType): string[] {
    return EVENT_MAP[event] ?? [];
  }

  mapNativeEvent(nativeEvent: string): HookEventType[] {
    return REVERSE_MAP[nativeEvent] ?? [];
  }

  async uninstall(): Promise<void> {
    await this.removeFile(HOOKS_RUNNER_PATH);
    await this.removeFile(HOOKS_CONFIG_PATH);
  }

  private generateRunner(): string {
    return `#!/usr/bin/env node
/**
 * ai-hooks runner for GitHub Copilot.
 * Generated by: ai-hooks generate
 *
 * Copilot passes hook event data as JSON via STDIN and reads JSON
 * from STDOUT (returning hookSpecificOutput.permissionDecision: "deny" on block).
 *
 * DO NOT EDIT - regenerate with: ai-hooks generate
 */
import { loadConfig, HookEngine } from "@itz4blitz/ai-tools-hooks";

const PROJECT_ROOT = ${JSON.stringify(resolve(process.cwd()))};
process.chdir(PROJECT_ROOT);

async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) {
    chunks.push(chunk);
  }
  return Buffer.concat(chunks).toString("utf-8");
}

function getMcpIdentity(toolName) {
  if (!toolName.startsWith("mcp__")) {
    return null;
  }
  const parts = toolName.split("__");
  return {
    server: parts[1] ?? "unknown",
    method: toolName,
  };
}

function parseToolArgs(raw) {
  if (typeof raw === "string") {
    try {
      const parsed = JSON.parse(raw);
      return parsed && typeof parsed === "object" ? parsed : { raw };
    } catch {
      return { raw };
    }
  }
  return raw && typeof raw === "object" ? raw : {};
}

function resolvePreToolUse(toolName, toolInput, timestamp, metadata) {
  const mcp = getMcpIdentity(toolName);
  if (mcp) {
    return {
      type: "mcp:before",
      server: mcp.server,
      method: mcp.method,
      params: toolInput,
      timestamp,
      metadata,
    };
  }

  switch (toolName) {
    case "Bash":
    case "bash":
    case "run_in_terminal":
      return {
        type: "shell:before",
        command: toolInput.command ?? "",
        cwd: toolInput.cwd ?? process.cwd(),
        timestamp,
        metadata,
      };
    case "Read":
    case "read_file":
      return {
        type: "file:read",
        path: toolInput.file_path ?? toolInput.filePath ?? toolInput.path ?? "",
        timestamp,
        metadata,
      };
    case "Write":
    case "create_file":
    case "write_file":
      return {
        type: "file:write",
        path: toolInput.file_path ?? toolInput.filePath ?? toolInput.path ?? "",
        content: toolInput.content ?? "",
        timestamp,
        metadata,
      };
    case "Edit":
    case "edit_file":
    case "replace_string_in_file":
      return {
        type: "file:edit",
        path: toolInput.file_path ?? toolInput.filePath ?? toolInput.path ?? "",
        oldContent: toolInput.old_string ?? toolInput.oldString ?? toolInput.oldContent ?? "",
        newContent: toolInput.new_string ?? toolInput.newString ?? toolInput.newContent ?? "",
        timestamp,
        metadata,
      };
    case "delete_file":
      return {
        type: "file:delete",
        path: toolInput.file_path ?? toolInput.filePath ?? toolInput.path ?? "",
        timestamp,
        metadata,
      };
    default:
      return {
        type: "tool:before",
        toolName: toolName || "unknown",
        input: toolInput,
        timestamp,
        metadata,
      };
  }
}

function resolvePostToolUse(toolName, toolInput, toolResponse, timestamp, metadata) {
  const mcp = getMcpIdentity(toolName);
  if (mcp) {
    return {
      type: "mcp:after",
      server: mcp.server,
      method: mcp.method,
      params: toolInput,
      result: toolResponse,
      duration: 0,
      timestamp,
      metadata,
    };
  }

  switch (toolName) {
    case "Bash":
    case "bash":
    case "run_in_terminal":
      return {
        type: "shell:after",
        command: toolInput.command ?? "",
        cwd: toolInput.cwd ?? process.cwd(),
        exitCode: toolResponse.exitCode ?? 0,
        stdout: toolResponse.stdout ?? "",
        stderr: toolResponse.stderr ?? "",
        duration: 0,
        timestamp,
        metadata,
      };
    default:
      return {
        type: "tool:after",
        toolName: toolName || "unknown",
        input: toolInput,
        output: toolResponse,
        duration: 0,
        timestamp,
        metadata,
      };
  }
}

function buildEvents(hookEventName, input, timestamp, metadata) {
  const toolName = input.tool_name ?? input.toolName ?? "";
  const toolInput = parseToolArgs(input.tool_input ?? input.toolArgs ?? input.input ?? {});
  const toolResponse = parseToolArgs(input.tool_response ?? input.toolResult ?? input.output ?? {});

  switch (hookEventName) {
    case "sessionStart":
      return [
        {
          type: "session:start",
          tool: "copilot",
          version: "1.0",
          workingDirectory: input.cwd ?? process.cwd(),
          timestamp,
          metadata,
        },
      ];
    case "userPromptSubmit":
      return [
        {
          type: "prompt:submit",
          prompt: input.prompt ?? "",
          timestamp,
          metadata,
        },
      ];
    case "preToolUse":
      return [resolvePreToolUse(toolName, toolInput, timestamp, metadata)];
    case "postToolUse":
      return [resolvePostToolUse(toolName, toolInput, toolResponse, timestamp, metadata)];
    case "stop": {
      const events = [];
      const responseText = input.last_assistant_message ?? input.response ?? "";
      if (typeof responseText === "string" && responseText.length > 0) {
        events.push({
          type: "prompt:response",
          response: responseText,
          model: input.model ?? "copilot",
          tokens: { input: 0, output: 0 },
          timestamp,
          metadata,
        });
      }
      events.push({
        type: "session:end",
        tool: "copilot",
        duration: 0,
        timestamp,
        metadata,
      });
      return events;
    }
    case "sessionEnd":
      return [
        {
          type: "session:end",
          tool: "copilot",
          duration: 0,
          timestamp,
          metadata,
        },
      ];
    default:
      return [];
  }
}

async function run() {
  let input = {};
  try {
    const raw = await readStdin();
    const parsed = JSON.parse(raw || "{}");
    input = parsed && typeof parsed === "object" && !Array.isArray(parsed) ? parsed : {};
  } catch {
    input = {};
  }

  const hookEventName = process.argv[2] ?? input.hookEventName ?? "";
  const config = await loadConfig();
  const engine = new HookEngine(config);
  const toolInfo = { name: "copilot", version: "1.0" };
  const timestamp = Date.now();
  const metadata = {};

  const events = buildEvents(hookEventName, input, timestamp, metadata);
  if (!events.length) {
    process.exit(0);
  }

  const results = [];
  for (const event of events) {
    const emitted = await engine.emit(event, toolInfo);
    results.push(...emitted);
  }

  const blocked = results.find((result) => result.blocked);
  if (blocked) {
    const reason = blocked.reason ?? "Blocked by ai-hooks";
    process.stdout.write(
      JSON.stringify({
        hookSpecificOutput: {
          hookEventName,
          permissionDecision: "deny",
          permissionDecisionReason: reason,
        },
      }),
    );
    process.exit(0);
  }

  const note = results.find((result) => result.data && result.data.additionalContext);
  if (note && (hookEventName === "userPromptSubmit" || hookEventName === "sessionStart")) {
    process.stdout.write(
      JSON.stringify({
        hookSpecificOutput: {
          hookEventName,
          additionalContext: note.data.additionalContext,
        },
      }),
    );
  }
}

run().catch((err) => {
  console.error("[ai-hooks] Error:", err.message);
  process.exit(1);
});
`;
  }
}

const adapter = new CopilotAdapter();
registry.register(adapter);

export { CopilotAdapter };
export default adapter;
