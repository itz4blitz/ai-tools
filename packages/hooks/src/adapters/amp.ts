import { existsSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import type {
  AdapterCapabilities,
  GeneratedConfig,
  HookDefinition,
  HookEventType,
} from "../types/index.js";
import { BaseAdapter, registry } from "./index.js";

const PLUGIN_PATH = ".amp/plugins/ai-tools-hooks.ts";

/**
 * Event mapping: ai-hooks universal events -> Amp plugin events.
 *
 * Amp supports TypeScript plugins in `.amp/plugins/` using `@ampcode/plugin`.
 * Plugins register lifecycle handlers via `amp.on(...)` and can block tool
 * calls by returning `{ action: "reject-and-continue", message }`.
 */
const EVENT_MAP: Record<string, string[]> = {
  "session:start": ["session.start"],
  "session:end": ["agent.end"],
  "prompt:submit": ["agent.start"],
  "prompt:response": ["agent.end"],
  "tool:before": ["tool.call"],
  "tool:after": ["tool.result"],
  "file:read": ["tool.call"],
  "file:write": ["tool.call"],
  "file:edit": ["tool.call"],
  "file:delete": ["tool.call"],
  "shell:before": ["tool.call"],
  "shell:after": ["tool.result"],
  "mcp:before": ["tool.call"],
  "mcp:after": ["tool.result"],
};

const REVERSE_MAP: Record<string, HookEventType[]> = {
  "session.start": ["session:start"],
  "agent.start": ["prompt:submit"],
  "agent.end": ["prompt:response", "session:end"],
  "tool.call": [
    "tool:before",
    "file:read",
    "file:write",
    "file:edit",
    "file:delete",
    "shell:before",
    "mcp:before",
  ],
  "tool.result": ["tool:after", "shell:after", "mcp:after"],
};

function resolveAmpUserSettingsPath(): string {
  const override = process.env.AMP_SETTINGS_FILE?.trim();
  if (override) return resolve(override);

  const xdgConfigHome = process.env.XDG_CONFIG_HOME?.trim();
  if (xdgConfigHome) return join(xdgConfigHome, "amp", "settings.json");

  return join(homedir(), ".config", "amp", "settings.json");
}

class AmpAdapter extends BaseAdapter {
  readonly id = "amp";
  readonly name = "Amp";
  readonly version = "1.0";

  readonly capabilities: AdapterCapabilities = {
    beforeHooks: true,
    afterHooks: true,
    mcp: true,
    configFile: true,
    supportedEvents: [
      "session:start",
      "session:end",
      "prompt:submit",
      "prompt:response",
      "tool:before",
      "tool:after",
      "file:read",
      "file:write",
      "file:edit",
      "file:delete",
      "shell:before",
      "shell:after",
      "mcp:before",
      "mcp:after",
    ],
    blockableEvents: [
      "tool:before",
      "file:read",
      "file:write",
      "file:edit",
      "file:delete",
      "shell:before",
      "mcp:before",
    ],
  };

  async detect(): Promise<boolean> {
    if (existsSync(resolve(process.cwd(), ".amp"))) return true;
    if (existsSync(resolveAmpUserSettingsPath())) return true;
    return this.commandExists("amp");
  }

  async generate(hooks: HookDefinition[]): Promise<GeneratedConfig[]> {
    const neededEvents = new Set<string>();
    for (const hook of hooks) {
      for (const event of hook.events) {
        for (const nativeEvent of this.mapEvent(event)) {
          neededEvents.add(nativeEvent);
        }
      }
    }

    return [
      {
        path: PLUGIN_PATH,
        content: this.generatePlugin(neededEvents),
        format: "ts",
      },
    ];
  }

  mapEvent(event: HookEventType): string[] {
    return EVENT_MAP[event] ?? [];
  }

  mapNativeEvent(nativeEvent: string): HookEventType[] {
    return REVERSE_MAP[nativeEvent] ?? [];
  }

  override async uninstall(): Promise<void> {
    await this.removeFile(PLUGIN_PATH);
  }

  private generatePlugin(neededEvents: Set<string>): string {
    const projectRoot = JSON.stringify(resolve(process.cwd()));
    const registrations = [...neededEvents]
      .map((eventName) => {
        if (eventName === "tool.call") {
          return `  amp.on("tool.call", async (event) => {
    return handleHook("tool.call", event);
  });`;
        }
        return `  amp.on(${JSON.stringify(eventName)}, async (event) => {
    await handleHook(${JSON.stringify(eventName)}, event);
  });`;
      })
      .join("\n\n");

    return `// @i-know-the-amp-plugin-api-is-wip-and-very-experimental-right-now
/**
 * ai-hooks plugin for Amp.
 * Generated by: ai-hooks generate
 *
 * Delegates Amp plugin lifecycle events to the ai-hooks engine.
 *
 * DO NOT EDIT - regenerate with: ai-hooks generate
 */
import type { PluginAPI } from "@ampcode/plugin";
import { loadConfig, HookEngine } from "@itz4blitz/ai-tools-hooks";

const PROJECT_ROOT = ${projectRoot};

let engine: HookEngine | undefined;

async function getEngine(): Promise<HookEngine> {
  if (!engine) {
    const config = await loadConfig(undefined, PROJECT_ROOT);
    engine = new HookEngine(config);
  }
  return engine;
}

function asRecord(value: unknown): Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {};
}

function resolveToolCall(payload: Record<string, unknown>, timestamp: number, metadata: Record<string, unknown>) {
  const toolName = String(payload.tool ?? payload.toolName ?? payload.name ?? "unknown");
  const input = asRecord(payload.input ?? payload.args);

  if (toolName.startsWith("mcp__")) {
    const [, serverName = "unknown", ...rest] = toolName.split("__");
    return {
      type: "mcp:before" as const,
      serverName,
      toolName: rest.join("__") || toolName,
      input,
      timestamp,
      metadata,
    };
  }

  switch (toolName.toLowerCase()) {
    case "bash":
    case "shell":
      return {
        type: "shell:before" as const,
        command: String(input.cmd ?? input.command ?? ""),
        cwd: String(input.cwd ?? PROJECT_ROOT),
        timestamp,
        metadata,
      };
    case "read":
    case "read_file":
      return {
        type: "file:read" as const,
        path: String(input.path ?? input.file_path ?? ""),
        timestamp,
        metadata,
      };
    case "create_file":
    case "write":
    case "write_file":
      return {
        type: "file:write" as const,
        path: String(input.path ?? input.file_path ?? ""),
        content: String(input.content ?? ""),
        timestamp,
        metadata,
      };
    case "edit_file":
    case "edit":
      return {
        type: "file:edit" as const,
        path: String(input.path ?? input.file_path ?? ""),
        oldContent: String(input.old_str ?? input.old ?? ""),
        newContent: String(input.new_str ?? input.new ?? ""),
        timestamp,
        metadata,
      };
    case "delete_file":
    case "delete":
      return {
        type: "file:delete" as const,
        path: String(input.path ?? input.file_path ?? ""),
        timestamp,
        metadata,
      };
    default:
      return {
        type: "tool:before" as const,
        toolName,
        input,
        timestamp,
        metadata,
      };
  }
}

function resolveToolResult(payload: Record<string, unknown>, timestamp: number, metadata: Record<string, unknown>) {
  const toolName = String(payload.tool ?? payload.toolName ?? payload.name ?? "unknown");
  const input = asRecord(payload.input ?? payload.args);
  const output = asRecord(payload.output ?? payload.result);

  if (toolName.startsWith("mcp__")) {
    const [, serverName = "unknown", ...rest] = toolName.split("__");
    return {
      type: "mcp:after" as const,
      serverName,
      toolName: rest.join("__") || toolName,
      input,
      output,
      duration: 0,
      timestamp,
      metadata,
    };
  }

  switch (toolName.toLowerCase()) {
    case "bash":
    case "shell":
      return {
        type: "shell:after" as const,
        command: String(input.cmd ?? input.command ?? ""),
        cwd: String(input.cwd ?? PROJECT_ROOT),
        exitCode: typeof output.exitCode === "number" ? output.exitCode : 0,
        stdout: String(output.stdout ?? ""),
        stderr: String(output.stderr ?? ""),
        duration: 0,
        timestamp,
        metadata,
      };
    default:
      return {
        type: "tool:after" as const,
        toolName,
        input,
        output,
        duration: 0,
        timestamp,
        metadata,
      };
  }
}

async function handleHook(eventName: string, rawEvent: unknown) {
  const eng = await getEngine();
  const toolInfo = { name: "amp", version: "1.0" };
  const timestamp = Date.now();
  const metadata: Record<string, unknown> = {};
  const payload = asRecord(rawEvent);

  const eventsToEmit = [];
  switch (eventName) {
    case "session.start":
      eventsToEmit.push({
        type: "session:start" as const,
        tool: "amp",
        version: "1.0",
        workingDirectory: PROJECT_ROOT,
        timestamp,
        metadata,
      });
      break;
    case "agent.start":
      eventsToEmit.push({
        type: "prompt:submit" as const,
        prompt: String(payload.message ?? payload.prompt ?? ""),
        timestamp,
        metadata,
      });
      break;
    case "agent.end":
      eventsToEmit.push(
        {
          type: "prompt:response" as const,
          response: String(payload.message ?? payload.response ?? ""),
          model: String(payload.model ?? "unknown"),
          tokens: { input: 0, output: 0 },
          timestamp,
          metadata,
        },
        {
          type: "session:end" as const,
          tool: "amp",
          duration: typeof payload.duration === "number" ? payload.duration : 0,
          timestamp,
          metadata,
        },
      );
      break;
    case "tool.call":
      eventsToEmit.push(resolveToolCall(payload, timestamp, metadata));
      break;
    case "tool.result":
      eventsToEmit.push(resolveToolResult(payload, timestamp, metadata));
      break;
    default:
      return;
  }

  for (const hookEvent of eventsToEmit) {
    const results = await eng.emit(hookEvent, toolInfo);
    const blocked = results.find((r) => r.blocked);

    if (blocked && eventName === "tool.call") {
      return {
        action: "reject-and-continue" as const,
        message: blocked.reason ?? "Blocked by ai-hooks",
      };
    }
  }
}

export default function (amp: PluginAPI) {
${registrations}
}
`;
  }
}

const adapter = new AmpAdapter();
registry.register(adapter);

export { AmpAdapter };
export default adapter;
