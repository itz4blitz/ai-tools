import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { BaseAdapter, registry } from "./index.js";
import { asRecord, collectNativeEvents, stringField } from "./claude-compat.js";
import type {
  AdapterCapabilities,
  GeneratedConfig,
  HookDefinition,
  HookEventType,
} from "../types/index.js";

/**
 * Event mapping: ai-hooks universal events -> Windsurf Cascade native hooks.
 *
 * Windsurf loads `.windsurf/hooks.json` with:
 *   { "hooks": { "<event>": [{ "command": "...", "show_output": true }] } }
 *
 * Blocking pre_* hooks return exit code 2.
 */
const EVENT_MAP: Record<string, string[]> = {
  "session:start": [],
  "session:end": [],
  "prompt:submit": ["pre_user_prompt"],
  "prompt:response": [],
  "tool:before": ["pre_mcp_tool_use"],
  "tool:after": ["post_mcp_tool_use"],
  "file:read": ["pre_read_code"],
  "file:write": ["pre_write_code", "post_write_code"],
  "file:edit": ["pre_write_code", "post_write_code"],
  "file:delete": [],
  "shell:before": ["pre_run_command"],
  "shell:after": ["post_run_command"],
  "mcp:before": ["pre_mcp_tool_use"],
  "mcp:after": ["post_mcp_tool_use"],
  notification: [],
};

const REVERSE_MAP: Record<string, HookEventType[]> = {
  pre_user_prompt: ["prompt:submit"],
  pre_read_code: ["file:read"],
  pre_write_code: ["file:write", "file:edit"],
  post_write_code: ["file:write", "file:edit"],
  pre_run_command: ["shell:before"],
  post_run_command: ["shell:after"],
  pre_mcp_tool_use: ["mcp:before", "tool:before"],
  post_mcp_tool_use: ["mcp:after", "tool:after"],
};

const HOOKS_JSON = ".windsurf/hooks.json";
const RUNNER_JS = ".windsurf/hooks/ai-tools-runner.js";

type WindsurfHookEntry = {
  command: string;
  show_output?: boolean;
  working_directory?: string;
};

class WindsurfAdapter extends BaseAdapter {
  readonly id = "windsurf";
  readonly name = "Windsurf";
  readonly version = "1.0";

  readonly capabilities: AdapterCapabilities = {
    beforeHooks: true,
    afterHooks: true,
    mcp: true,
    configFile: true,
    supportedEvents: [
      "prompt:submit",
      "file:read",
      "file:write",
      "file:edit",
      "shell:before",
      "shell:after",
      "mcp:before",
      "mcp:after",
      "tool:before",
      "tool:after",
    ],
    blockableEvents: [
      "prompt:submit",
      "file:read",
      "file:write",
      "file:edit",
      "shell:before",
      "mcp:before",
      "tool:before",
    ],
  };

  async detect(): Promise<boolean> {
    if (await this.commandExists("windsurf")) return true;
    if (existsSync(resolve(process.cwd(), ".windsurf"))) return true;
    if (existsSync(join(homedir(), ".codeium", "windsurf"))) return true;
    return false;
  }

  async generate(hooks: HookDefinition[]): Promise<GeneratedConfig[]> {
    const nativeEvents = collectNativeEvents(hooks, (event) => this.mapEvent(event));
    const merged = await this.mergeHooksConfig(nativeEvents);

    return [
      {
        path: HOOKS_JSON,
        content: `${JSON.stringify(merged, null, 2)}\n`,
        format: "json",
      },
      {
        path: RUNNER_JS,
        content: this.generateRunner(),
        format: "js",
      },
    ];
  }

  async import(cwd?: string): Promise<HookDefinition[]> {
    const dir = cwd ?? process.cwd();
    const data = await this.readJsonRecord(resolve(dir, HOOKS_JSON));
    const hooksMap = asRecord(data.hooks);
    const imported: HookDefinition[] = [];

    for (const [nativeEvent, rawEntries] of Object.entries(hooksMap)) {
      if (!Array.isArray(rawEntries)) continue;
      const events = this.mapNativeEvent(nativeEvent);
      if (events.length === 0) continue;
      const phase: "before" | "after" = nativeEvent.startsWith("pre_") ? "before" : "after";

      rawEntries.forEach((rawEntry, index) => {
        const entry = asRecord(rawEntry);
        const command = stringField(entry.command);
        if (!command) return;
        imported.push({
          id: `windsurf-${nativeEvent}-${index}`,
          name: command,
          description: `windsurf ${nativeEvent}`,
          events,
          phase,
          handler: async (_ctx, next) => {
            await next();
          },
        });
      });
    }

    return imported;
  }

  mapEvent(event: HookEventType): string[] {
    return EVENT_MAP[event] ?? [];
  }

  mapNativeEvent(nativeEvent: string): HookEventType[] {
    return REVERSE_MAP[nativeEvent] ?? [];
  }

  override async uninstall(): Promise<void> {
    await this.removeFile(RUNNER_JS);
    await this.stripHooksFile();
  }

  private generateRunner(): string {
    return `#!/usr/bin/env node
/**
 * ai-hooks runner for Windsurf Cascade.
 * Generated by: ai-hooks generate
 *
 * Windsurf sends the hook event as JSON on stdin. Blocking pre_* hooks deny with exit 2.
 *
 * DO NOT EDIT - regenerate with: ai-hooks generate
 */
import { runWindsurfHook } from "@itz4blitz/ai-tools-hooks";

const PROJECT_ROOT = ${JSON.stringify(resolve(process.cwd()))};
process.chdir(PROJECT_ROOT);

process.exit(await runWindsurfHook());
`;
  }

  private async mergeHooksConfig(nativeEvents: string[]): Promise<Record<string, unknown>> {
    const existing = await this.readJsonRecord(resolve(process.cwd(), HOOKS_JSON));
    const existingHooks = asRecord(existing.hooks);
    const mergedHooks: Record<string, unknown[]> = {};

    for (const [event, entries] of Object.entries(existingHooks)) {
      const kept = stripAiHooksEntries(entries);
      if (kept.length > 0) {
        mergedHooks[event] = kept;
      }
    }

    const runnerPath = resolve(process.cwd(), RUNNER_JS);
    for (const nativeEvent of nativeEvents) {
      const current = mergedHooks[nativeEvent] ?? [];
      const entry: WindsurfHookEntry = {
        command: `node ${JSON.stringify(runnerPath)} ${nativeEvent}`,
        show_output: true,
      };
      mergedHooks[nativeEvent] = [...current, entry];
    }

    return {
      ...existing,
      hooks: mergedHooks,
    };
  }

  private async stripHooksFile(): Promise<void> {
    const fullPath = resolve(process.cwd(), HOOKS_JSON);
    if (!existsSync(fullPath)) return;

    const existing = await this.readJsonRecord(fullPath);
    if (Object.keys(existing).length === 0) return;

    const existingHooks = asRecord(existing.hooks);
    const stripped: Record<string, unknown[]> = {};
    for (const [event, entries] of Object.entries(existingHooks)) {
      const kept = stripAiHooksEntries(entries);
      if (kept.length > 0) stripped[event] = kept;
    }

    const otherTopLevelKeys = Object.keys(existing).filter((key) => key !== "hooks");
    if (Object.keys(stripped).length === 0 && otherTopLevelKeys.length === 0) {
      await this.removeFile(HOOKS_JSON);
      return;
    }

    await this.writeJsonFile(HOOKS_JSON, {
      ...existing,
      hooks: stripped,
    });
  }

  private async readJsonRecord(fullPath: string): Promise<Record<string, unknown>> {
    if (!existsSync(fullPath)) return {};
    try {
      const parsed: unknown = JSON.parse(await readFile(fullPath, "utf-8"));
      if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
        return parsed as Record<string, unknown>;
      }
    } catch {
      return {};
    }
    return {};
  }
}

function stripAiHooksEntries(entries: unknown): unknown[] {
  if (!Array.isArray(entries)) return [];
  return entries.filter((entry) => {
    const command = asRecord(entry).command;
    return !(typeof command === "string" && command.includes("ai-tools-runner.js"));
  });
}

const adapter = new WindsurfAdapter();
registry.register(adapter);

export { WindsurfAdapter };
export default adapter;
